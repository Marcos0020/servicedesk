-- ============================================================
-- TABLE: USERS (Technicians and admins)
-- ============================================================
CREATE TABLE users (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR2(150)  NOT NULL,
    email          VARCHAR2(255)  NOT NULL UNIQUE,
    password_hash  VARCHAR2(255)  NOT NULL,
    role           VARCHAR2(20)   DEFAULT 'technician' NOT NULL,
        -- Allowed: 'admin', 'supervisor', 'technician'
    is_active      NUMBER(1)      DEFAULT 1 NOT NULL,
    created_at     TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at     TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_user_role CHECK (role IN ('admin', 'supervisor', 'technician')),
    CONSTRAINT chk_user_active CHECK (is_active IN (0, 1))
);

CREATE INDEX idx_users_email ON users(email);

COMMENT ON TABLE users IS 'System users: admins and technicians';
COMMENT ON COLUMN users.role IS 'admin = full access; supervisor = ticket delegation and monitoring; technician = execute assigned tickets';

-- ============================================================
-- TABLE: TICKETS (Core service desk tickets)
-- ============================================================
CREATE TABLE tickets (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR2(500)  NOT NULL,
    description     CLOB,
    requester_name  VARCHAR2(200),
    requester_email VARCHAR2(255),
    type            VARCHAR2(30)   DEFAULT 'COMUM' NOT NULL,
        -- Allowed: 'COMUM', 'COMPLEXO'
    status          VARCHAR2(30)   DEFAULT 'ABERTO' NOT NULL,
        -- Allowed: 'ABERTO', 'EM_ANDAMENTO', 'FINALIZADO'
    responsible_id  NUMBER,        -- FK to users
    source          VARCHAR2(20)   DEFAULT 'MANUAL' NOT NULL,
        -- Allowed: 'MANUAL', 'EMAIL'
    email_message_id VARCHAR2(500) UNIQUE,
        -- Gmail Message-ID for idempotency (avoids duplicate tickets)
    created_at      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    finalized_at    TIMESTAMP,
    CONSTRAINT chk_ticket_type   CHECK (type IN ('COMUM', 'COMPLEXO')),
    CONSTRAINT chk_ticket_status CHECK (status IN ('ABERTO', 'EM_ANDAMENTO', 'FINALIZADO')),
    CONSTRAINT chk_ticket_source CHECK (source IN ('MANUAL', 'EMAIL')),
    CONSTRAINT fk_ticket_responsible
        FOREIGN KEY (responsible_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_tickets_status      ON tickets(status);
CREATE INDEX idx_tickets_responsible ON tickets(responsible_id);
CREATE INDEX idx_tickets_created     ON tickets(created_at);
CREATE INDEX idx_tickets_email_msgid ON tickets(email_message_id);
CREATE INDEX idx_tickets_requester   ON tickets(requester_email);

COMMENT ON TABLE tickets IS 'Service desk tickets - created manually or via email';
COMMENT ON COLUMN tickets.email_message_id IS 'Gmail unique Message-ID used to prevent duplicate ticket creation';

-- ============================================================
-- TABLE: ATTACHMENTS (Files linked to tickets)
-- ============================================================
CREATE TABLE attachments (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     NUMBER         NOT NULL,
    original_name VARCHAR2(500)  NOT NULL,
    stored_name   VARCHAR2(500)  NOT NULL, -- UUID-based filename on disk
    file_path     VARCHAR2(1000) NOT NULL, -- Relative path in storage folder
    mime_type     VARCHAR2(200),
    file_size     NUMBER         DEFAULT 0,
    uploaded_by   NUMBER,        -- FK to users (NULL if from email)
    created_at    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_attachment_ticket
        FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
    CONSTRAINT fk_attachment_uploader
        FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_attachments_ticket ON attachments(ticket_id);

COMMENT ON TABLE attachments IS 'Files attached to tickets (images, Excel, Word, etc.)';

-- ============================================================
-- TABLE: EMAIL_BLACKLIST (Blocked sender emails)
-- ============================================================
CREATE TABLE email_blacklist (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR2(255) NOT NULL UNIQUE,
    reason     VARCHAR2(500),
    created_by NUMBER,        -- FK to users
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_blacklist_creator
        FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_blacklist_email ON email_blacklist(email);

COMMENT ON TABLE email_blacklist IS 'Blocked sender emails - emails from these addresses are ignored';

-- ============================================================
-- TABLE: LOGS (Audit log for ticket and system events)
-- ============================================================
CREATE TABLE logs (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity     VARCHAR2(50)   NOT NULL, -- 'ticket', 'user', 'email', 'backup'
    entity_id  NUMBER,
    action     VARCHAR2(100)  NOT NULL, -- 'created', 'status_changed', 'assigned', etc.
    old_value  CLOB,
    new_value  CLOB,
    performed_by NUMBER,       -- FK to users
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_log_user
        FOREIGN KEY (performed_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_logs_entity    ON logs(entity, entity_id);
CREATE INDEX idx_logs_created   ON logs(created_at);
CREATE INDEX idx_logs_performer ON logs(performed_by);

COMMENT ON TABLE logs IS 'Audit trail for all system events';

-- ============================================================
-- TABLE: BACKUP_JOBS (Track scheduled backups)
-- ============================================================
CREATE TABLE backup_jobs (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR2(20) NOT NULL, -- 'database', 'files', 'full'
    status       VARCHAR2(20) NOT NULL DEFAULT 'PENDING',
        -- 'PENDING', 'RUNNING', 'SUCCESS', 'FAILED'
    file_path    VARCHAR2(1000),
    file_size    NUMBER DEFAULT 0,
    error_msg    CLOB,
    started_at   TIMESTAMP,
    finished_at  TIMESTAMP,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_backup_status CHECK (status IN ('PENDING','RUNNING','SUCCESS','FAILED')),
    CONSTRAINT chk_backup_type   CHECK (type IN ('database','files','full'))
);

COMMENT ON TABLE backup_jobs IS 'Log of scheduled and manual backup executions';

-- ============================================================
-- TRIGGER: Auto-update updated_at on tickets
-- ============================================================
CREATE OR REPLACE TRIGGER trg_tickets_updated_at
BEFORE UPDATE ON tickets
FOR EACH ROW
BEGIN
    :NEW.updated_at := CURRENT_TIMESTAMP;
    -- Set finalized_at when status changes to FINALIZADO
    IF :NEW.status = 'FINALIZADO' AND :OLD.status != 'FINALIZADO' THEN
        :NEW.finalized_at := CURRENT_TIMESTAMP;
    END IF;
END;
/

-- ============================================================
-- TRIGGER: Auto-update updated_at on users
-- ============================================================
CREATE OR REPLACE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
BEGIN
    :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/

