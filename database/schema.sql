-- View: tickets with responsible user name
CREATE OR REPLACE VIEW vw_tickets AS
SELECT
    t.id,
    t.title,
    t.description,
    t.requester_name,
    t.requester_email,
    t.type,
    t.status,
    t.source,
    t.created_at,
    t.updated_at,
    t.finalized_at,
    u.id   AS responsible_id,
    u.name AS responsible_name,
    u.email AS responsible_email
FROM tickets t
LEFT JOIN users u ON u.id = t.responsible_id;

-- View: ticket counts by status (dashboard)
CREATE OR REPLACE VIEW vw_ticket_summary AS
SELECT
    COUNT(*) AS total,
    SUM(CASE WHEN status = 'ABERTO'       THEN 1 ELSE 0 END) AS abertos,
    SUM(CASE WHEN status = 'EM_ANDAMENTO' THEN 1 ELSE 0 END) AS em_andamento,
    SUM(CASE WHEN status = 'FINALIZADO'   THEN 1 ELSE 0 END) AS finalizados,
    SUM(CASE WHEN type   = 'COMPLEXO'     THEN 1 ELSE 0 END) AS complexos
FROM tickets;

